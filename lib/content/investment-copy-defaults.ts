const LABEL_KEYS = new Map<string, keyof typeof INVESTMENT_COPY_DEFAULTS>(Object.entries(INVESTMENT_COPY_DEFAULTS).map(([key, value]) => [value, key as keyof typeof INVESTMENT_COPY_DEFAULTS]));
export function investmentLabel(value: string, text: (key: keyof typeof INVESTMENT_COPY_DEFAULTS) => string): string {
  const key = LABEL_KEYS.get(value);
  return key ? text(key) : value;
}

// Replace each placeholder once so inserted fund names cannot be interpreted as placeholders.
export function investmentValue(template: string, values: readonly unknown[]): string {
  return template.replace(/\{value(\d+)\}/g, (_, index: string) => String(values[Number(index) - 1]));
}
